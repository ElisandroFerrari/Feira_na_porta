create or replace function public.create_customer_order(
  p_items jsonb,
  p_phone text,
  p_street text,
  p_house_number text,
  p_neighborhood text,
  p_city text,
  p_note text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  item record;
  product_name text;
  unit_price numeric(10, 2);
  item_subtotal numeric(10, 2);
  calculated_total numeric(10, 2) := 0;
  saved_items jsonb := '[]'::jsonb;
  saved_order_id uuid;
  customer_name text;
begin
  if current_user_id is null then
    raise exception 'Entre na sua conta para finalizar o pedido.';
  end if;
  if jsonb_typeof(p_items) is distinct from 'array' then
    raise exception 'O carrinho está vazio.';
  end if;
  if jsonb_array_length(p_items) = 0 then
    raise exception 'O carrinho está vazio.';
  end if;
  if nullif(trim(p_phone), '') is null or nullif(trim(p_street), '') is null
     or nullif(trim(p_house_number), '') is null or nullif(trim(p_neighborhood), '') is null
     or nullif(trim(p_city), '') is null then
    raise exception 'Preencha telefone e todos os dados de entrega.';
  end if;
  if char_length(trim(p_phone)) > 20 or char_length(trim(p_street)) > 120
     or char_length(trim(p_house_number)) > 20 or char_length(trim(p_neighborhood)) > 80
     or char_length(trim(p_city)) > 80 or char_length(coalesce(p_note, '')) > 300 then
    raise exception 'Um ou mais campos excedem o limite permitido.';
  end if;

  select full_name into customer_name
  from public.profiles
  where user_id = current_user_id and role = 'customer';
  if not found then
    raise exception 'Perfil de cliente não encontrado.';
  end if;

  for item in
    select * from jsonb_to_recordset(p_items) as requested(product_id bigint, unidade text, quantidade integer)
  loop
    if item.product_id is null or item.quantidade is null or item.quantidade < 1 or item.quantidade > 100 then
      raise exception 'O carrinho contém uma quantidade ou produto inválido.';
    end if;
    select p.nome, pp.preco into product_name, unit_price
    from public.produtos p
    join public.precos_produto pp on pp.produto_id = p.id
    where p.id = item.product_id and pp.unidade = item.unidade;
    if not found then
      raise exception 'Um produto do carrinho não está mais disponível. Atualize a página e tente novamente.';
    end if;
    item_subtotal := unit_price * item.quantidade;
    calculated_total := calculated_total + item_subtotal;
    saved_items := saved_items || jsonb_build_array(jsonb_build_object(
      'product_id', item.product_id,
      'nome', product_name,
      'unidade', item.unidade,
      'quantidade', item.quantidade,
      'preco', unit_price,
      'subtotal', item_subtotal
    ));
  end loop;

  insert into public.orders (
    user_id, customer_name, customer_email, phone, street, house_number,
    neighborhood, city, note, items, total
  )
  values (
    current_user_id, customer_name, coalesce(auth.jwt() ->> 'email', ''), trim(p_phone),
    trim(p_street), trim(p_house_number), trim(p_neighborhood), trim(p_city),
    coalesce(trim(p_note), ''), saved_items, calculated_total
  )
  returning id into saved_order_id;

  return jsonb_build_object(
    'id', saved_order_id,
    'items', saved_items,
    'total', calculated_total,
    'customer_name', customer_name,
    'customer_email', coalesce(auth.jwt() ->> 'email', '')
  );
end;
$$;
revoke all on function public.create_customer_order(jsonb, text, text, text, text, text, text) from public, anon;
grant execute on function public.create_customer_order(jsonb, text, text, text, text, text, text) to authenticated;

