  created_at timestamptz not null default now()
);

create unique index if not exists precos_produto_unidade_unica
  on public.precos_produto (produto_id, lower(trim(unidade)));

-- Move existing single-price products before removing the legacy columns.
do $$
declare
  has_unidade boolean;
  has_preco boolean;
begin
  select exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'produtos' and column_name = 'unidade'
  ) into has_unidade;

  select exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'produtos' and column_name = 'preco'
  ) into has_preco;

  if has_unidade <> has_preco then
    raise exception
      'Migração interrompida: produtos possui apenas uma das colunas antigas (unidade/preco).';
  end if;

  if has_unidade and has_preco then
    execute $migration$
      insert into public.precos_produto (produto_id, unidade, preco)
      select p.id, trim(p.unidade), p.preco
      from public.produtos p
      where p.unidade is not null
        and char_length(trim(p.unidade)) between 1 and 40
        and p.preco is not null
        and p.preco > 0
        and not exists (
          select 1
          from public.precos_produto pp
          where pp.produto_id = p.id
            and lower(trim(pp.unidade)) = lower(trim(p.unidade))
        )
    $migration$;

    alter table public.produtos
      drop column unidade,
      drop column preco;
  end if;
end;
$$;

