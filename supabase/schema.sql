create or replace function public.save_product_with_prices(
  p_product_id bigint,
  p_nome text,
  p_descricao text,
  p_categoria text,
  p_imagem text,
  p_precos jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  saved_product_id bigint;
begin
  if jsonb_typeof(p_precos) is distinct from 'array' then
    raise exception 'Informe as opções de preço em uma lista.';
  end if;
  if jsonb_array_length(p_precos) = 0 then
    raise exception 'Informe pelo menos uma opção de preço.';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_precos) as price(unidade text, preco numeric)
    where price.unidade is null
      or char_length(trim(price.unidade)) not between 1 and 40
      or price.preco is null
      or price.preco <= 0
  ) then
    raise exception 'Cada opção precisa ter uma unidade válida e um preço maior que zero.';
  end if;

  if exists (
    select lower(trim(price.unidade))
    from jsonb_to_recordset(p_precos) as price(unidade text, preco numeric)
    group by lower(trim(price.unidade))
    having count(*) > 1
  ) then
    raise exception 'Cada opção precisa ter um tipo de unidade diferente.';
  end if;

  if p_product_id is null then
    insert into public.produtos (nome, descricao, categoria, imagem)
    values (trim(p_nome), coalesce(p_descricao, ''), trim(p_categoria), p_imagem)
    returning id into saved_product_id;
  else
    update public.produtos
    set nome = trim(p_nome),
        descricao = coalesce(p_descricao, ''),
        categoria = trim(p_categoria),
        imagem = p_imagem
    where id = p_product_id
    returning id into saved_product_id;

    if saved_product_id is null then
      raise exception 'Produto não encontrado ou sem permissão para edição.';
    end if;
  end if;

  delete from public.precos_produto where produto_id = saved_product_id;
  insert into public.precos_produto (produto_id, unidade, preco, ordem)
  select saved_product_id, trim(price.unidade), price.preco, (price.ordinality - 1)::integer
  from jsonb_to_recordset(p_precos) with ordinality
    as price(unidade text, preco numeric, ordinality bigint)
  order by price.ordinality;

  return saved_product_id;
end;
$$;

revoke all on function public.save_product_with_prices(bigint, text, text, text, text, jsonb) from public, anon;
grant execute on function public.save_product_with_prices(bigint, text, text, text, text, jsonb) to authenticated;

